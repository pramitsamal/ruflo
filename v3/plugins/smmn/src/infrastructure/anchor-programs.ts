export class AnchorProgramError extends Error {
  constructor(program: string, cause: unknown) {
    super(`Anchor program error [${program}]: ${String(cause)}`);
    this.name = 'AnchorProgramError';
  }
}

/** Creates a read-only AnchorProvider (no wallet required for reads) */
function createReadProvider(connection: Connection): AnchorProvider {
  // Minimal wallet stub for read-only operations
  const wallet = {
    publicKey: PublicKey.default,
    signTransaction: async <T>(tx: T) => tx,
    signAllTransactions: async <T>(txs: T[]) => txs,
  };
  return new AnchorProvider(connection, wallet as unknown as Wallet, {
    commitment: 'confirmed',
    preflightCommitment: 'confirmed',
  });
}

