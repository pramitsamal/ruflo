/**
 * Build a backerRound initialize instruction.
 */
export async function buildInitializeBackerRoundIx(
  program: Program,
  roundAccount: PublicKey,
  authority: PublicKey,
  totalSlots: number,
  slotPriceUsd: number,
  platformFeeBps: number,
  deadline: Date
): Promise<ReturnType<typeof program.methods.initialize>> {
  return program.methods
    .initialize(
      totalSlots,
      new BN(slotPriceUsd * 100), // store as cents
      platformFeeBps,
      new BN(Math.floor(deadline.getTime() / 1000))
    )
    .accounts({
      backerRound: roundAccount,
      authority,
    });
}

/**
 * Build a purchaseSlot instruction.
 */
export async function buildPurchaseSlotIx(
  program: Program,
  roundAccount: PublicKey,
  backer: PublicKey
): Promise<ReturnType<typeof program.methods.purchaseSlot>> {
  return program.methods.purchaseSlot().accounts({
    backerRound: roundAccount,
    backer,
  });
}
